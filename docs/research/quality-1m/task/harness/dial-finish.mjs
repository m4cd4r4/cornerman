#!/usr/bin/env node
// dial-finish.mjs: waits for a running fork arm to end, then parks it, scores it, runs
// compare.mjs --fork over every parked fork, writes DIAL-PILOT.md and commits + pushes it.
//   node dial-finish.mjs <fork name>
// Exits 0 when everything ran, 2 when the run ended INVALID or unfinished (nothing scored).
import { execFileSync, spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const QDIR = resolve(HERE, "..", "..");
const REPO = resolve(QDIR, "..", "..", "..");
const name = process.argv[2];
if (!name) throw new Error("need a fork name");
const LIVE = "I:/Scratch/_q1m/default-sonnet-r3", LOCK = "I:/Scratch/_q1m/.lock";
const sleep = (ms) => new Promise((ok) => setTimeout(ok, ms));
const say = (s) => console.log(`${new Date().toISOString()} ${s}`);
const node = (args) => spawnSync(process.execPath, args, { encoding: "utf8", maxBuffer: 1 << 26 });

while (existsSync(LOCK) || !existsSync(join(LIVE, "out", "ended.txt"))) await sleep(60000);
const ended = readFileSync(join(LIVE, "out", "ended.txt"), "utf8").trim();
say(`run ended: ${ended}`);
await sleep(90000); // let the 30 s monitors see the end line and exit, so no handle blocks the rename

let parked = false;
for (let i = 0; i < 10 && !parked; i++) {
  const r = node([join(HERE, "fork.mjs"), "park", name]);
  parked = r.status === 0;
  say(parked ? r.stdout.trim() : `park try ${i + 1} failed: ${(r.stderr || "").split("\n").find((l) => /Error/.test(l))}`);
  if (!parked) await sleep(30000);
}
if (!parked) { say("STOP: could not park"); process.exit(1); }

const P = join("I:/Scratch/_q1m-fork", name);
if (existsSync(join(P, "out", "INVALID")) || !/finished true/.test(ended)) {
  say(`STOP: ${name} is INVALID or unfinished, not scored: ${existsSync(join(P, "out", "INVALID")) ? readFileSync(join(P, "out", "INVALID"), "utf8").trim() : ended}`);
  process.exit(2);
}

const s = node([join(HERE, "fork.mjs"), "score", name]);
say(`score exit ${s.status}\n${s.stdout.split("\n").slice(-16).join("\n")}`);
if (s.status !== 0) { say(s.stderr); process.exit(1); }

const md = join(QDIR, "DIAL-PILOT.md");
const c = node([join(QDIR, "task", "tools", "compare.mjs"), "--fork", "--md", join(P, "compare.md")]);
say(`compare exit ${c.status}\n${c.stdout}`);
const score = (n) => JSON.parse(readFileSync(join("I:/Scratch/_q1m-fork", n, "score.json"), "utf8")).summary;
const rows = ["fork-natural-sonnet-r3", name].map((n) => { const x = score(n); return `| ${n} | ${x.latePassed}/${x.lateTotal} | ${x.chat.passed}/${x.chat.total} | ${x.tokens?.compactions} | ${x.tokens?.peak} | ${x.regressions} |`; });
writeFileSync(md, [
  "# Fill-dial pilot result (generated by harness/dial-finish.mjs; not yet reviewed)", "",
  `Generated ${new Date().toISOString()}. Pilot 3 reference on cp44-80: 33/37, chat 12/14.`, "",
  "| Run | cp44-80 hidden | Chat | Compactions | Peak context | Regressions |", "|:--|--:|--:|--:|--:|--:|", ...rows, "",
  "compare.mjs --fork:", "", c.stdout.trim(), "",
].join("\n"));
const git = (...a) => execFileSync("git", ["-C", REPO, ...a], { encoding: "utf8" });
git("add", md);
git("commit", "-q", "-m", `docs(quality-1m): dial pilot scored (${name})`, "-m", "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>");
git("push", "-q", "origin", "research/quality-1m");
say(`committed and pushed ${md}`);
